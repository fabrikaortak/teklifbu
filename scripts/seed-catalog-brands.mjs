function leafSlugs(sub) {
  return [`ikinci-el-${sub}`, `sifir-urun-${sub}`];
}

async function main() {
  // Smoke / test artıkları
  const deletedSmoke = await prisma.brand.deleteMany({
    where: {
      OR: [{ slug: { startsWith: "samsung-smoke" } }, { slug: { contains: "-tmp" } }],
    },
  });
  console.log("deleted_smoke", deletedSmoke.count);

  /** slug → { name, sortOrder } */
  const global = new Map();
  let sort = 0;
  for (const pairs of Object.values(BY_SUB)) {
    for (const [slug, name] of pairs) {
      if (!global.has(slug)) {
        global.set(slug, { name, sortOrder: sort++ });
      }
    }
  }

  let upserted = 0;
  for (const [slug, meta] of global) {
    await prisma.brand.upsert({
      where: { slug },
      create: {
        slug,
        name: meta.name,
        sortOrder: meta.sortOrder,
        isActive: true,
        deletedAt: null,
      },
      update: {
        name: meta.name,
        isActive: true,
        deletedAt: null,
        sortOrder: meta.sortOrder,
      },
    });
    upserted++;
  }
  console.log("brands_upserted", upserted);

  const brandBySlug = Object.fromEntries(
    (await prisma.brand.findMany({ select: { id: true, slug: true } })).map((b) => [b.slug, b.id])
  );

  let links = 0;
  let missingCats = 0;
  for (const [sub, pairs] of Object.entries(BY_SUB)) {
    for (const leaf of leafSlugs(sub)) {
      const cat = await prisma.category.findUnique({ where: { slug: leaf }, select: { id: true } });
      if (!cat) {
        missingCats++;
        continue;
      }
      let order = 0;
      for (const [slug] of pairs) {
        const brandId = brandBySlug[slug];
        if (!brandId) continue;
        const sortOrder = order++;
        await prisma.categoryBrand.upsert({
          where: { categoryId_brandId: { categoryId: cat.id, brandId } },
          create: {
            categoryId: cat.id,
            brandId,
            sortOrder,
            isFeatured: sortOrder < 6,
          },
          update: {
            sortOrder,
            isFeatured: sortOrder < 6,
          },
        });
        links++;
      }
    }
  }

  console.log("category_brand_links", links);
  console.log("missing_category_leaves", missingCats);
  console.log("total_brands", await prisma.brand.count({ where: { deletedAt: null } }));
  console.log("total_links", await prisma.categoryBrand.count());
}

main()
  .catch((e) => {
    console.error(e);
    process.exitCode = 1;
  })
  .finally(() => prisma.$disconnect());
